"""Build a deterministic source archive of LunarLab, with a manifest of SHA-256 digests.

    python tools/build_source_archive.py --rev HEAD            # release candidate from a commit
    python tools/build_source_archive.py --working-tree        # include uncommitted files (labelled as such)
    python tools/build_source_archive.py --rev HEAD --verify   # also extract, install and test it

Writes ``dist/lunarlab-<version>-src.tar.gz``, ``…-src.manifest.json`` and ``SHA256SUMS``. Nothing is published.

Contents: the repository's files (``git archive`` of the revision, or tracked plus new non-ignored files of the
working tree), excluding version-control files (.gitignore and the like), editor settings, the derived web-demo snapshot (``demo/api/``,
~25 MB, regenerated by ``export-demo``) and the manuscript sources (``paper/``, submitted separately). Platform
metadata files (``.DS_Store``, ``Thumbs.db``, ``._*``) and environment files (``.env*``) are refused.

Determinism: members are sorted, owners and permissions normalised, every timestamp is the revision's commit
time, gzip carries no name or time, and working-tree text files are normalised to LF exactly as git stores them,
so the same revision always gives the same archive bytes. JMLR names the published archive after the paper
(for example ``jones03a-code.tar.gz``); rename the file once that identifier is assigned.
"""

from __future__ import annotations

import argparse
import fnmatch
import gzip
import hashlib
import io
import json
import os
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXCLUDED_PREFIXES = ("demo/api/", "paper/", ".vscode/")
EXCLUDED_FILES = (".gitignore", ".gitattributes", ".gitmodules")
REFUSED_PATTERNS = (".DS_Store", "Thumbs.db", "desktop.ini", "._*", ".env", ".env.*", "*.pyc")


def _git(*args: str, binary: bool = False):
    out = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, check=True)
    return out.stdout if binary else out.stdout.decode("utf-8")


def version() -> str:
    ns: dict = {}
    for line in (ROOT / "lunarlab" / "__init__.py").read_text(encoding="utf-8").splitlines():
        if line.startswith("__version__"):
            exec(line, ns)  # a single literal assignment
    return ns["__version__"]


def _excluded(path: str) -> bool:
    return path.startswith(EXCLUDED_PREFIXES) or path in EXCLUDED_FILES


def _refused(path: str) -> bool:
    name = path.rsplit("/", 1)[-1]
    return any(fnmatch.fnmatch(name, p) for p in REFUSED_PATTERNS) or "/.git/" in f"/{path}"


def _as_git_stores(data: bytes) -> bytes:
    """git's text rule (no NUL in the first 8000 bytes) with core.autocrlf: text is stored with LF."""
    return data if b"\0" in data[:8000] else data.replace(b"\r\n", b"\n")


def _byte_exact(paths: list[str]) -> set[str]:
    """Paths whose ``text`` attribute is unset in .gitattributes: git stores them byte for byte."""
    if not paths:
        return set()
    out = (
        subprocess.run(
            ["git", "check-attr", "-z", "--stdin", "text"],
            cwd=ROOT,
            input="\0".join(paths).encode("utf-8"),
            capture_output=True,
            check=True,
        )
        .stdout.decode("utf-8")
        .split("\0")
    )
    return {out[i] for i in range(0, len(out) - 2, 3) if out[i + 2] == "unset"}


def collect(rev: str | None) -> tuple[dict[str, bytes], dict]:
    """Return {path: bytes} and a description of the source."""
    files: dict[str, bytes] = {}
    if rev:
        commit = _git("rev-parse", rev).strip()
        with tarfile.open(fileobj=io.BytesIO(_git("archive", "--format=tar", commit, binary=True))) as tf:
            for m in tf.getmembers():
                if m.isfile():
                    files[m.name] = tf.extractfile(m).read()
        epoch = int(_git("log", "-1", "--format=%ct", commit).strip())
        source = {"mode": "revision", "revision": commit, "dirty": False}
    else:
        commit = _git("rev-parse", "HEAD").strip()
        listed = [
            p for p in _git("ls-files", "--cached", "--others", "--exclude-standard", "-z").split("\0") if p
        ]
        exact = _byte_exact(listed)
        for path in listed:
            p = ROOT / path
            if p.is_file():  # tracked files deleted in the working tree are skipped
                data = p.read_bytes()
                files[path] = data if path in exact else _as_git_stores(data)
        epoch = int(_git("log", "-1", "--format=%ct", "HEAD").strip())
        dirty = bool(_git("status", "--porcelain").strip())
        source = {"mode": "working-tree", "revision": commit, "dirty": dirty}
    refused = sorted(p for p in files if _refused(p))
    if refused:
        raise SystemExit(f"refusing to package platform-metadata or environment files: {refused}")
    excluded = sorted(p for p in files if _excluded(p))
    kept = {p: d for p, d in files.items() if not _excluded(p)}
    source.update(
        source_date_epoch=epoch, excluded_files=len(excluded), excluded_prefixes=list(EXCLUDED_PREFIXES)
    )
    return kept, source


def build(files: dict[str, bytes], source: dict, out: Path) -> dict:
    v = version()
    top = f"lunarlab-{v}"
    epoch = source["source_date_epoch"]
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.PAX_FORMAT) as tf:
        dirs = sorted({f"{top}/{p}".rsplit("/", 1)[0] for p in files} | {top})
        all_dirs = sorted({"/".join(d.split("/")[: i + 1]) for d in dirs for i in range(len(d.split("/")))})
        for d in all_dirs:
            info = tarfile.TarInfo(d)
            info.type, info.mode, info.mtime = tarfile.DIRTYPE, 0o755, epoch
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            tf.addfile(info)
        for path in sorted(files):
            data = files[path]
            info = tarfile.TarInfo(f"{top}/{path}")
            info.size, info.mode, info.mtime = len(data), 0o644, epoch
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            tf.addfile(info, io.BytesIO(data))
    out.mkdir(parents=True, exist_ok=True)
    archive = out / f"{top}-src.tar.gz"
    with (
        archive.open("wb") as fh,
        gzip.GzipFile(filename="", mode="wb", fileobj=fh, mtime=0, compresslevel=9) as gz,
    ):
        gz.write(raw.getvalue())
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    manifest = {
        "name": "lunarlab",
        "version": v,
        "archive": {"file": archive.name, "size": archive.stat().st_size, "sha256": digest},
        "source": source,
        "built_with": {"python": sys.version.split()[0], "tool": "tools/build_source_archive.py"},
        "n_files": len(files),
        "total_bytes": sum(len(d) for d in files.values()),
        "files": [
            {"path": p, "size": len(files[p]), "sha256": hashlib.sha256(files[p]).hexdigest()}
            for p in sorted(files)
        ],
    }
    (out / f"{top}-src.manifest.json").write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8")
    (out / "SHA256SUMS").write_text(f"{digest}  {archive.name}\n", encoding="utf-8")
    return manifest


def verify(archive: Path, *, python: str = "3.12") -> None:
    """Extract the archive into a temporary folder, install it into a fresh virtual environment, and run
    ``--version``, ``doctor``, ``reproduce-smoke`` and the release-relevant tests from the extracted tree."""
    lock = "requirements.lock" if sys.platform == "win32" else "requirements-ci.lock"
    with tempfile.TemporaryDirectory(prefix="lunarlab-sdist-") as tmp:
        tmp_path = Path(tmp)
        with tarfile.open(archive) as tf:
            tf.extractall(tmp_path, filter="data")
        src = next(tmp_path.iterdir())
        names = {p.relative_to(src).as_posix() for p in src.rglob("*") if p.is_file()}
        assert "LICENSE" in names and "THIRD_PARTY_NOTICES.md" in names, "license files missing"
        vcs = [n for n in names if n.startswith(".git/") or n in EXCLUDED_FILES]
        assert not vcs, f"version-control files present: {vcs}"
        venv = tmp_path / "venv"
        py = venv / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
        extra = [] if sys.platform == "win32" else ["--torch-backend", "cpu"]
        steps = [
            ["uv", "venv", "--python", python, str(venv)],
            ["uv", "pip", "install", "--python", str(py), "-r", str(src / lock), *extra],
            ["uv", "pip", "install", "--python", str(py), "--no-deps", str(src)],
            [str(py), "-m", "lunarlab", "--version"],
            [str(py), "-m", "lunarlab", "doctor"],
            [str(py), "-m", "lunarlab", "reproduce-smoke", "--transitions", "2048"],
            [str(py), "-m", "pytest", "-q", "-p", "no:cacheprovider",
             "tests/test_project_metadata.py", "tests/test_docs.py", "tests/test_reproduce.py",
             "tests/test_audit_core.py", "tests/test_properties.py", "tests/test_rewards.py"],
        ]  # fmt: skip
        env = {
            **os.environ,
            "SDL_VIDEODRIVER": "dummy",
            "SDL_AUDIODRIVER": "dummy",
            "LUNARLAB_HOME": str(tmp_path / "home"),
        }
        env.pop("VIRTUAL_ENV", None)
        for cmd in steps:
            print("$", " ".join(Path(c).name if os.sep in c or "/" in c else c for c in cmd), flush=True)
            res = subprocess.run(cmd, cwd=src, env=env, capture_output=True, text=True)
            tail = (res.stdout + res.stderr).strip().splitlines()[-3:]
            print("   " + "\n   ".join(tail), flush=True)
            if res.returncode != 0:
                raise SystemExit(f"verification failed at: {' '.join(cmd)}")
    print("verified: the archive installs, runs and passes its release tests in a fresh environment")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = ap.add_mutually_exclusive_group()
    group.add_argument("--rev", help="git revision to package (default HEAD)")
    group.add_argument(
        "--working-tree", action="store_true", help="package the working tree, uncommitted files included"
    )
    ap.add_argument("--out", default=str(ROOT / "dist"))
    ap.add_argument("--verify", action="store_true", help="extract, install into a fresh venv and test")
    args = ap.parse_args()
    files, source = collect(None if args.working_tree else (args.rev or "HEAD"))
    m = build(files, source, Path(args.out))
    a = m["archive"]
    print(
        f"{a['file']}: {m['n_files']} files, {a['size'] / 1e6:.1f} MB, sha256 {a['sha256']}\n"
        f"source: {source['mode']} {source['revision'][:12]}{' (uncommitted changes included)' if source['dirty'] else ''}"
    )
    if args.verify:
        verify(Path(args.out) / a["file"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
