"""Write THIRD_PARTY_NOTICES.md from the dependency locks and the packages' published metadata.

    python tools/third_party_notices.py            # rewrite THIRD_PARTY_NOTICES.md (needs network)
    python tools/third_party_notices.py --check    # exit 1 if the file is out of date

Python packages: every pin in requirements.lock, with the license declared in that exact release's
metadata on PyPI (License-Expression, else the License field, else the license classifiers), so the
output is the same on every machine. Frontend packages: the production dependency closure in
frontend/package-lock.json (the code that can end up in the built web UI), with each package's
declared license. Nothing here is guessed.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9_.\-]*)==([^\s;]+)")

HEADER = """# Third-party notices

LunarLab's own code is released under the MIT License (see [LICENSE](LICENSE)). LunarLab does not
copy third-party source code into this repository; it depends on the packages listed below, which are
installed from PyPI and npm under their own licenses. This file is generated by
`python tools/third_party_notices.py` from `requirements.lock`, the installed package metadata and
`frontend/package-lock.json`; `--check` verifies it is current.

## Components used without being redistributed in the source package

| Component | How LunarLab uses it | License |
|---|---|---|
| Gymnasium `LunarLander-v3` (Farama Foundation) | the environment; its renderer draws the simulator footage in `docs/media/showcase.gif` and in recordings; `HeuristicPolicy` calls Gymnasium's own `heuristic` function (imported, not copied) | MIT |
| IBM Plex Sans and IBM Plex Mono fonts (via `@fontsource`) | bundled by Vite into the built web UI and the hosted demo | SIL Open Font License 1.1 |
| JMLR LaTeX style file `jmlr2e.sty` | fetched by `paper/jmlr-mloss/fetch_style.py` when building the manuscript; **not** included in this repository because its repository declares no license | not stated by its publisher |

Media and data in this repository (`docs/media/`, `docs/results/`, `demo/api/`) were produced by
LunarLab from its own experiment runs.
"""


def python_license(name: str, version: str) -> str:
    """The license declared in the metadata of this exact release on PyPI."""
    req = urllib.request.Request(
        f"https://pypi.org/pypi/{name}/{version}/json", headers={"User-Agent": "lunarlab-notices"}
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        info = json.load(resp)["info"]
    expr = (info.get("license_expression") or "").strip()
    if expr:
        return expr
    lic = (info.get("license") or "").strip()
    classifiers = [
        c.split("::")[-1].strip() for c in info.get("classifiers") or [] if c.startswith("License ::")
    ]
    if lic and len(lic) <= 80 and "\n" not in lic:
        return lic
    if classifiers:
        return "; ".join(classifiers)
    if lic:
        return lic.splitlines()[0][:80] + " (see the package's license text)"
    return "not declared in the package metadata"


def python_rows() -> list[tuple[str, str, str, str]]:
    pins = []
    for line in (ROOT / "requirements.lock").read_text(encoding="utf-8").splitlines():
        m = PIN.match(line.strip())
        if m:
            marker = line.split(";", 1)[1].strip() if ";" in line else ""
            pins.append((m.group(1), m.group(2), marker))
    with ThreadPoolExecutor(max_workers=8) as pool:
        licenses = list(pool.map(lambda p: python_license(p[0], p[1]), pins))
    rows = [(n, v, lic, marker) for (n, v, marker), lic in zip(pins, licenses, strict=True)]
    return sorted(rows, key=lambda r: r[0].lower())


def frontend_rows() -> list[tuple[str, str, str]]:
    lock = json.loads((ROOT / "frontend" / "package-lock.json").read_text(encoding="utf-8"))
    rows = []
    for path, info in lock.get("packages", {}).items():
        if not path or info.get("dev") or info.get("devOptional"):
            continue
        name = path.split("node_modules/")[-1]
        lic = info.get("license") or "not declared in package-lock.json"
        rows.append((name, info.get("version", "?"), lic))
    return sorted(set(rows), key=lambda r: r[0].lower())


def render() -> str:
    out = [HEADER]
    py = python_rows()
    linux_only = [r for r in py if "sys_platform == 'linux'" in r[3]]
    proprietary = [r for r in linux_only if "proprietary" in r[2].lower()]
    undeclared = [r for r in linux_only if r[2].startswith("not declared")]
    out.append(
        f"\n## Python packages ({len(py)} pins in `requirements.lock`, installed from PyPI)\n\n"
        f"{len(linux_only)} pins are installed **on Linux only** (marker `sys_platform == 'linux'`): the NVIDIA "
        "CUDA runtime that PyPI's default `torch` wheel pulls in, and Triton. On PyPI, "
        f"{len(proprietary)} of them declare a proprietary NVIDIA license and {len(undeclared)} declare no license "
        "in their metadata. LunarLab does not use CUDA by default and does not need any of them: the CPU-only lock "
        "`requirements-ci.lock` (used by CI and recommended for Linux) contains none of them, and PyPI's Windows "
        "`torch` wheels are CPU builds without them.\n\n"
        "| Package | Version | License (declared on PyPI for this release) | Installed when |\n|---|---|---|---|"
    )
    out += [f"| {n} | {v} | {lic} | {m.replace('|', '/') or 'always'} |" for n, v, lic, m in py]
    fe = frontend_rows()
    out.append(
        f"\n## Frontend packages ({len(fe)} production packages in `frontend/package-lock.json`)\n\n"
        "These can be bundled into the built web UI (`frontend/dist/`) and the hosted demo. Development-only "
        "packages (build tools, type definitions, Playwright) are not bundled and not listed.\n\n"
        "| Package | Version | License (from package-lock.json) |\n|---|---|---|"
    )
    out += [f"| {n} | {v} | {lic} |" for n, v, lic in fe]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if THIRD_PARTY_NOTICES.md is out of date")
    args = ap.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(
                "THIRD_PARTY_NOTICES.md is out of date: run python tools/third_party_notices.py",
                file=sys.stderr,
            )
            return 1
        print("THIRD_PARTY_NOTICES.md is current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
